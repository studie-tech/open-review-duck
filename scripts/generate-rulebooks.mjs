import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const rulebookDirectory = join(
  repositoryRoot,
  "src",
  "server",
  "review",
  "deep",
  "rulebooks",
);
const documentDirectory = join(rulebookDirectory, "docs");
const outputPath = join(rulebookDirectory, "corpus.generated.ts");

/**
 * Reads the vendored path map, preserving its authored key order.
 *
 * Upstream resolves rules by first match in document order rather than by
 * specificity, so `.github/workflows/**` must keep beating `.github/**`, which
 * must keep beating `**` for the same extension. Emitting an ordered array
 * freezes that at generation time instead of relying on object key order.
 */
function readPathRuleMap() {
  const source = readFileSync(
    join(rulebookDirectory, "system-rules.json"),
    "utf8",
  );
  const parsed = JSON.parse(source);
  return {
    defaultRule: parsed.default_rule,
    entries: Object.entries(parsed.path_rule_map),
  };
}

/** Reads every vendored rulebook keyed by its file name. */
function readDocuments() {
  return readdirSync(documentDirectory)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => [name, readFileSync(join(documentDirectory, name), "utf8")]);
}

const { defaultRule, entries } = readPathRuleMap();
const documents = readDocuments();

const missing = [defaultRule, ...entries.map(([, name]) => name)].filter(
  (name) => !documents.some(([document]) => document === name),
);
if (missing.length > 0) {
  throw new Error(
    `system-rules.json references missing rulebooks: ${missing.join(", ")}`,
  );
}

const digest = createHash("sha256");
digest.update(defaultRule);
for (const [pattern, name] of entries) digest.update(`${pattern}\0${name}\0`);
for (const [name, body] of documents) digest.update(`${name}\0${body}\0`);

const banner = [
  "// Generated by scripts/generate-rulebooks.mjs. Do not edit.",
  "//",
  "// The rulebooks themselves are vendored from alibaba/open-code-review under",
  "// Apache-2.0; see ./LICENSE and ./NOTICE in this directory. They are embedded",
  "// here rather than read from disk so that resolution behaves identically under",
  "// vitest, next dev, a traced standalone build, and the Docker appliance.",
  "",
].join("\n");

const body = [
  banner,
  `export const RULEBOOK_DEFAULT = ${JSON.stringify(defaultRule)};`,
  "",
  "export const RULEBOOK_PATTERNS: ReadonlyArray<readonly [string, string]> = [",
  ...entries.map(
    ([pattern, name]) =>
      `  [${JSON.stringify(pattern)}, ${JSON.stringify(name)}],`,
  ),
  "];",
  "",
  "export const RULEBOOK_DOCUMENTS: Readonly<Record<string, string>> = {",
  ...documents.map(
    ([name, text]) => `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`,
  ),
  "};",
  "",
  `export const RULEBOOK_DIGEST = ${JSON.stringify(digest.digest("hex"))};`,
  "",
].join("\n");

writeFileSync(outputPath, body);
process.stdout.write(
  `Generated ${documents.length} rulebooks and ${entries.length} patterns.\n`,
);
